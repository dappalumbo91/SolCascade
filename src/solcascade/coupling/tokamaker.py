"""TokaMaker handoff.

TokaMaker, from the Open FUSION Toolkit, solves the Grad-Shafranov equation.
It needs a mesh and a plasma boundary. SolCascade does not invent those.
The generated script imports TokaMaker when ``OFT_ROOTPATH`` or an installed
``OpenFUSIONToolkit`` package provides it, prints the coil set, and stops
before a solve unless a mesh path was configured. The vacuum-field metrics
from the Python pipeline remain the equilibrium result either way.
"""

from __future__ import annotations

from pathlib import Path

from solcascade.geometry.coils import CoilSet


def tokamaker_status() -> dict:
    try:
        from OpenFUSIONToolkit.TokaMaker import TokaMaker  # noqa: F401
    except Exception as exc:
        return {"importable": False, "reason": str(exc)}
    return {"importable": True}


def write_script(path: Path, coils: CoilSet, mesh: str | None) -> None:
    rows = []
    for coil in coils.coils:
        rows.append(
            f"    ({coil.name!r}, {coil.radius_m!r}, {coil.z_m!r}, "
            f"{coil.turns!r}, {coil.current_a!r}),"
        )
    table = "\n".join(rows)
    mesh_literal = "None" if not mesh else repr(mesh)
    path.write_text(
        "\n".join(
            [
                '"""Generated by SolCascade. Optional TokaMaker equilibrium."""',
                "import os",
                "import sys",
                "",
                "root = os.environ.get('OFT_ROOTPATH')",
                "if root:",
                "    sys.path.append(os.path.join(root, 'python'))",
                "",
                "coils = [",
                table,
                "]",
                f"mesh = os.environ.get('SOLCASCADE_TOKAMAKER_MESH', {mesh_literal})",
                "",
                "try:",
                "    from OpenFUSIONToolkit.TokaMaker import TokaMaker",
                "except Exception as exc:",
                "    print('TokaMaker is not importable:', exc)",
                "    print('SolCascade already recorded the vacuum coil field.')",
                "    raise SystemExit(0)",
                "",
                "print('TokaMaker imported:', TokaMaker)",
                "print('Coils (name, radius_m, z_m, turns, current_a):')",
                "for row in coils:",
                "    print(row)",
                "if not mesh:",
                "    print('No mesh configured. Not solving Grad-Shafranov.')",
                "    raise SystemExit(0)",
                "print('Mesh path:', mesh)",
                "print('Build a gs_Domain on this mesh before calling TokaMaker.solve.')",
                "print('SolCascade does not invent a plasma boundary.')",
                "raise SystemExit(0)",
                "",
            ]
        ),
        encoding="utf-8",
    )
