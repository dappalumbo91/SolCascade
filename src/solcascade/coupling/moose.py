"""MOOSE heat-conduction input for the same shell the native solver uses.

The mesh is one-dimensional with ``coord_type = RSPHERICAL``. The source is
the cell-wise power density, written as a nested ``if`` so it is piecewise
constant on the native cells. Properties are piecewise constant by layer.

This file targets the open MOOSE heat-transfer module. SolCascade always
solves the same problem in Python. It runs ``moose`` only when an executable
is configured and the run is requested.
"""

from __future__ import annotations

import os
import subprocess
from pathlib import Path

import numpy as np

from solcascade.geometry.shell import Shell
from solcascade.materials.library import Material


def write_heat_input(
    path: Path,
    shell: Shell,
    library: dict[str, Material],
    source_w_m3: np.ndarray,
    duration_s: float,
    steps: int,
    initial_temperature_k: float,
    sink_temperature_k: float,
    heat_transfer_coefficient: float,
) -> None:
    faces = shell.face_radii_m()
    dt = duration_s / steps if steps else duration_s
    conductivity = [library[cell.material].thermal_conductivity_W_mK for cell in shell.cells]
    density = [library[cell.material].density_kg_m3 for cell in shell.cells]
    specific_heat = [library[cell.material].specific_heat_J_kgK for cell in shell.cells]
    text = "\n".join(
        [
            "# Generated by SolCascade. Open MOOSE heat-transfer module.",
            "# 1D spherical shell. Source is W/m^3, piecewise constant per cell.",
            "# The native Python transient is the result the pipeline reports.",
            "[Mesh]",
            "  [gen]",
            "    type = GeneratedMeshGenerator",
            "    dim = 1",
            f"    xmin = {_num(faces[0])}",
            f"    xmax = {_num(faces[-1])}",
            f"    nx = {len(shell.cells)}",
            "  []",
            "  coord_type = RSPHERICAL",
            "[]",
            "[Variables]",
            "  [T]",
            f"    initial_condition = {_num(initial_temperature_k)}",
            "  []",
            "[]",
            "[Functions]",
            "  [volumetric_heating]",
            "    type = ParsedFunction",
            f"    expression = '{_piecewise(faces, source_w_m3)}'",
            "  []",
            "  [k_of_r]",
            "    type = ParsedFunction",
            f"    expression = '{_piecewise(faces, conductivity)}'",
            "  []",
            "  [rho_of_r]",
            "    type = ParsedFunction",
            f"    expression = '{_piecewise(faces, density)}'",
            "  []",
            "  [cp_of_r]",
            "    type = ParsedFunction",
            f"    expression = '{_piecewise(faces, specific_heat)}'",
            "  []",
            "[]",
            "[Kernels]",
            "  [time]",
            "    type = SpecificHeatConductionTimeDerivative",
            "    variable = T",
            "  []",
            "  [conduction]",
            "    type = HeatConduction",
            "    variable = T",
            "  []",
            "  [source]",
            "    type = BodyForce",
            "    variable = T",
            "    function = volumetric_heating",
            "  []",
            "[]",
            "[BCs]",
            "  [outer]",
            "    type = ConvectiveHeatFluxBC",
            "    variable = T",
            "    boundary = right",
            f"    T_infinity = {_num(sink_temperature_k)}",
            f"    heat_transfer_coefficient = {_num(heat_transfer_coefficient)}",
            "  []",
            "[]",
            "[Materials]",
            "  [shell]",
            "    type = GenericFunctionMaterial",
            "    prop_names = 'thermal_conductivity density specific_heat'",
            "    prop_values = 'k_of_r rho_of_r cp_of_r'",
            "  []",
            "[]",
            "[Postprocessors]",
            "  [T_inner]",
            "    type = SideAverageValue",
            "    variable = T",
            "    boundary = left",
            "  []",
            "  [T_outer]",
            "    type = SideAverageValue",
            "    variable = T",
            "    boundary = right",
            "  []",
            "[]",
            "[Executioner]",
            "  type = Transient",
            "  scheme = bdf2",
            f"  end_time = {_num(duration_s)}",
            f"  dt = {_num(dt)}",
            "  solve_type = NEWTON",
            "[]",
            "[Outputs]",
            "  csv = true",
            "  exodus = true",
            "[]",
            "",
        ]
    )
    path.write_text(text, encoding="utf-8")


def run_moose(executable: str | None, input_path: Path, workdir: Path) -> dict:
    exe = executable or os.environ.get("SOLCASCADE_MOOSE_EXE")
    if not exe:
        return {
            "executed": False,
            "reason": "No MOOSE executable. Set heat.moose_executable or SOLCASCADE_MOOSE_EXE.",
        }
    if not Path(exe).is_file():
        return {"executed": False, "reason": f"MOOSE executable not found: {exe}"}
    completed = subprocess.run(
        [exe, "-i", input_path.name],
        cwd=workdir,
        capture_output=True,
        text=True,
        check=False,
    )
    log = workdir / "moose.log"
    log.write_text(completed.stdout + "\n" + completed.stderr, encoding="utf-8")
    return {
        "executed": completed.returncode == 0,
        "returncode": completed.returncode,
        "executable": exe,
        "log": str(log),
    }


def _num(value: float) -> str:
    return format(float(value), ".16g")


def _piecewise(faces: np.ndarray, values) -> str:
    expression = _num(float(values[-1]))
    for index in range(len(values) - 2, -1, -1):
        expression = f"if(x<{_num(float(faces[index + 1]))},{_num(float(values[index]))},{expression})"
    return expression
