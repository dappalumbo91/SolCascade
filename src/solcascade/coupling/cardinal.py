"""Cardinal coupling note.

Cardinal is the open MOOSE application that wraps OpenMC. A full Cardinal
input depends on the application's mesh-to-cell mapping, which is specific
to a built Cardinal executable. SolCascade writes the numbers that mapping
would consume and a short skeleton marked as a skeleton.
"""

from __future__ import annotations

from pathlib import Path


def write_skeleton(
    path: Path,
    particles: int,
    batches: int,
    source_rate_per_s: float,
    heat_input_name: str,
) -> None:
    path.write_text(
        "\n".join(
            [
                "# Generated by SolCascade. SKELETON, not a validated Cardinal deck.",
                "# Cardinal wraps OpenMC inside MOOSE so the heating tally can",
                "# become the source term of a MOOSE heat solve. The Python",
                "# pipeline already passes that source term in heat_conduction.i.",
                "# Fill the cell mapping against your Cardinal build before running.",
                "[Problem]",
                "  type = OpenMCCellAverageProblem",
                f"  particles = {int(particles)}",
                f"  batches = {int(batches)}",
                "  inactive = 0",
                f"  # Fixed-source rate from the SolCascade pulse average: {source_rate_per_s:.8g} 1/s",
                "  cell_level = 0",
                "[]",
                "[MultiApps]",
                "  [heat]",
                "    type = FullSolveMultiApp",
                "    app_type = MooseApp",
                f"    input_files = '{heat_input_name}'",
                "    execute_on = timestep_end",
                "  []",
                "[]",
                "",
            ]
        ),
        encoding="utf-8",
    )
